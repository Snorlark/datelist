/**
 * Two weeks of both calendars (Oct 5 – Oct 18). "Busy" blocks only; private
 * events are shown to the other person as busy without a title.
 */
const ev = (
  owner: CalendarEvent["owner"],
  day: string,
  start: string,
  end: string,
  title: string,
  priv = false,
): CalendarEvent => ({
  id: `${owner}-${day}-${start}`,
  owner,
  day,
  start,
  end,
  title,
  private: priv,
});

const weekdayWork = (owner: CalendarEvent["owner"], days: string[], start: string, end: string) =>
  days.map((d) => ev(owner, d, start, end, "Work"));

